# Applied on hasu to a scratch copy (measure-tree) only: TSC stamps across kmain_console's IDT-less window.
import sys
p = sys.argv[1] + '/kernel/kmain_console.lu'; s = open(p).read()
def edit(old, new):
    global s
    assert s.count(old) == 1, old[:60]; s = s.replace(old, new)
edit('extern "c" let pax_user_thread: *u8\n', 'extern "c" let pax_user_thread: *u8\nextern "c" fn pax_rdtsc() -> u64\nfn tsc() -> u64 { unsafe { pax_rdtsc() } }\n')
edit('''    triage.start()
    triage.step(2)
    serial.init()''', '''    let t0 = tsc()
    triage.start()
    triage.step(2)
    serial.init()
    let t1 = tsc()''')
edit('''    frames.start()
    triage.step(4)''', '''    frames.start()
    let t2 = tsc()
    triage.step(4)''')
edit('''    let pml4 = paging.build() // paging.start's three steps, a box between each''', '''    let pml4 = paging.build() // paging.start's three steps, a box between each
    let t3 = tsc()''')
edit('''    paging.switch_to(pml4)
    triage.step(6) // PAX's page tables live''', '''    paging.switch_to(pml4)
    let t4 = tsc()
    triage.step(6) // PAX's page tables live''')
edit('''    triage.step(7)
    // px76: its mode''', '''    let t5 = tsc()
    triage.step(7)
    // px76: its mode''')
edit('''    triage.step(8)
    interrupts.start()''', '''    let t6 = tsc()
    let sc = screen.scrolls()
    triage.step(8)
    interrupts.start()
    let t7 = tsc()
    log.put("window: tsc serial+screen "); log.dec((t1 - t0) as int)
    log.put(" frames "); log.dec((t2 - t1) as int)
    log.put(" build "); log.dec((t3 - t2) as int)
    log.put(" switch "); log.dec((t4 - t3) as int)
    log.put(" fb "); log.dec((t5 - t4) as int)
    log.put(" initramfs "); log.dec((t6 - t5) as int)
    log.put(" idt "); log.dec((t7 - t6) as int)
    log.put(" total "); log.dec((t7 - t0) as int)
    log.put(" scrolls "); log.dec(sc as int)
    log.end()''')
open(p, 'w').write(s)
