out.append("/* The triage font: 5x7 glyphs for ASCII 0x20-0x5f, one byte a row (bit 4 the left");
out.append("   column), seven rows a glyph, generated by notes/px77d/font.py. */")
out.append("        .section .rodata")
out.append("        .globl pax_triage_font")
out.append("pax_triage_font:")
for c in range(0x20, 0x60):
    ch = chr(c)
    rows = G.get(ch, ["#####","#   #","#   #","#   #","#   #","#   #","#####"] if ch not in G else None)
    assert all(len(r)==5 for r in rows), ch
    bs = [sum(1<<(4-i) for i,x in enumerate(r) if x=='#') for r in rows]
    out.append("        .byte " + ", ".join(f"0x{b:02x}" for b in bs) + f"    /* {repr(ch)} */")
print("\n".join(out))
