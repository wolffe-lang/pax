#!/usr/bin/env python3
"""px59: tests/mpx5-screen.d/vtcases.py from the two VT probes' sources
(notes/px59/vtprobe.c, vtprobe2.c): every screen(), emit() and answer()
call of each probe's main(), in order, as the bytes the VT was sent.
The suite replays them through tools/screen-ref (and PAX's screen) and
holds each snapshot to the VT's rows (tests/mpx5-screen.d/vt*.rows).
    mkcases.py OUT.py"""
import pathlib, re, sys

here = pathlib.Path(__file__).resolve().parent

def cstr(body):
    out, i = bytearray(), 0
    while i < len(body):
        c = body[i]
        if c != '\\':
            out += c.encode(); i += 1; continue
        n = body[i + 1]
        if n in '01234567':
            j = i + 1
            while j < len(body) and j < i + 4 and body[j] in '01234567':
                j += 1
            out.append(int(body[i + 1:j], 8)); i = j
        elif n == 'x':
            j = i + 2
            while j < len(body) and body[j] in '0123456789abcdefABCDEF':
                j += 1
            out.append(int(body[i + 2:j], 16)); i = j
        else:
            out += {'n': b'\n', 'r': b'\r', 't': b'\t', '\\': b'\\', '"': b'"', 'a': b'\a', 'b': b'\b'}[n]; i += 2
    return bytes(out)

def calls(path):
    src = path.read_text()
    main = src[src.index('int main(void)'):]
    main = main[:main.index('const char *keys') if 'const char *keys' in main and 'for (unsigned i' not in main[:main.index('const char *keys')] else len(main)]
    out = []
    pal = main.find('for(int bg=0;bg<2;bg++)')
    pat = r'\b(screen|emit|answer|cells)\(((?:"[^"\\]*(?:\\.[^"\\]*)*"\s*,?\s*)+)\)\s*;'
    for m in re.finditer(pat, main):
        if pal >= 0 and m.start() > pal:
            # vtprobe.c's PALETTE loop: a clear, then 256 cells of
            # `ESC [ 0 ; 38|48 ; 5 ; i m X`, the foreground run first.
            out.append(('palette', 'FG', b''))
            out.append(('palette', 'BG', b''))
            pal = -1
            if m.group(1) == 'emit':
                continue
        lits = [cstr(x) for x in re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(2))]
        kind = m.group(1)
        if kind == 'emit':
            out.append(('emit', None, b''.join(lits)))
        elif kind == 'cells':
            # vtprobe2.c's ECHO rows: the emit before is a query sent in
            # canonical mode with ECHO and ECHOCTL; the line discipline
            # echoes the VT's answer (the suite feeds the echo after it).
            k, _n, b = out.pop()
            assert k == 'emit'
            out.append(('echo', lits[1].decode(), b))
        else:
            out.append((kind, lits[0].decode(), b''.join(lits[1:])))
    return out

with open(sys.argv[1], 'w') as f:
    f.write('# Generated by notes/px59/mkcases.py from notes/px59/vtprobe.c and vtprobe2.c:\n'
            '# each probe\'s screen(), emit() and answer() calls, in order (a probe is one\n'
            '# boot of a Linux VT; its PALETTE loop is vtprobe.c\'s, replayed by the suite).\n'
            '# screen() sends CLEAR then the bytes and reads the screen; answer() flushes the\n'
            '# input, sends the bytes and reads the answer.\n')
    f.write('CLEAR = %r\n' % b'\033[0m\033[2J\033[H')
    for name, probe in (('PROBE1', 'vtprobe.c'), ('PROBE2', 'vtprobe2.c')):
        f.write('%s = [\n' % name)
        for c in calls(here / probe):
            f.write('    %r,\n' % (c,))
        f.write(']\n')
